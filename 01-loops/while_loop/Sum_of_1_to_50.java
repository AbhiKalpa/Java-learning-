package while_loop;
import java.util.Scanner;

public class Sum_of_1_to_50 {
    public static void main(String[] args){
        Scanner sc = new Scanner(System.in);
     int i=0;
       while(i<=50){
           for(i =0; i<=50 ;i++) {
               System.out.println(i);
           }
       }
       sc.close();
    }
}